       jsonb_build_object('canonical_name',m.canonical_name,'source_name',m.source_name,'method','verified roster alias'),true
from map m
join public.clubs c on c.slug='maccabi-bnot-ashdod'
join public.players pc on lower(pc.name)=lower(m.canonical_name)
join public.players ps on ps.name=m.source_name
on conflict (club_id,canonical_player_id,source_player_id) do update
set confidence=excluded.confidence,evidence=excluded.evidence,verified=true;

create or replace function public.player_360_snapshot(p_club_id bigint,p_player_id bigint,p_season text default null)
returns jsonb
language plpgsql stable security definer set search_path=public
as $$
declare
  result jsonb;
begin
  if not private.is_club_member(p_club_id) then raise exception 'not authorized'; end if;
  if not exists (select 1 from public.club_players cp where cp.club_id=p_club_id and cp.player_id=p_player_id) then
    raise exception 'player is not in this club workspace';
  end if;
  with ids as (
    select p_player_id as id
    union
    select source_player_id from public.player_identity_links where club_id=p_club_id and canonical_player_id=p_player_id and verified=true
  ), base as (
    select p.id,p.name,p.position,p.nationality,p.source_url,p.analysis,cp.season,cp.roster_status
    from public.players p join public.club_players cp on cp.player_id=p.id and cp.club_id=p_club_id
    where p.id=p_player_id
  ), samples as (
    select coalesce(jsonb_agg(to_jsonb(s) order by s.season desc,s.created_at desc),'[]'::jsonb) j
    from public.player_samples s where s.player_id in (select id from ids) and (p_season is null or s.season=p_season)
  ), games as (
    select coalesce(jsonb_agg(jsonb_build_object(
      'id',g.id,'game_id',g.game_id,'season',g.season,'competition',g.competition,'team_name',g.team_name,
      'opponent_name',g.opponent_name,'player_name',g.player_name,'starter',g.starter,'minutes',g.minutes,
      'stats',g.stats,'calculated',g.calculated,'source_url',g.source_url,'created_at',g.created_at
    ) order by g.created_at desc),'[]'::jsonb) j
    from public.game_player_stats g where g.player_id in (select id from ids) and g.verified=true and (p_season is null or g.season=p_season)
  ), aliases as (
    select coalesce(jsonb_agg(jsonb_build_object('source_player_id',l.source_player_id,'source_label',l.source_label,'confidence',l.confidence,'evidence',l.evidence,'verified',l.verified)),'[]'::jsonb) j
    from public.player_identity_links l where l.club_id=p_club_id and l.canonical_player_id=p_player_id
  )
  select jsonb_build_object('player',to_jsonb(base),'aliases',aliases.j,'samples',samples.j,'game_stats',games.j)
  into result from base,samples,games,aliases;
  return coalesce(result,'{}'::jsonb);
end;$$;

create or replace function public.basketball_ops_snapshot(p_club_id bigint,p_season text default null)
returns jsonb
language plpgsql stable security definer set search_path=public
as $$
declare result jsonb;
begin
  if not private.is_club_member(p_club_id) then raise exception 'not authorized'; end if;
  with club_players_json as (
    select coalesce(jsonb_agg(jsonb_build_object(
      'club_id',cp.club_id,'player_id',cp.player_id,'season',cp.season,'roster_status',cp.roster_status,
      'player',jsonb_build_object('id',p.id,'name',p.name,'position',p.position,'nationality',p.nationality,'source_url',p.source_url,'analysis',p.analysis),
      'source_ids',coalesce((select jsonb_agg(l.source_player_id) from public.player_identity_links l where l.club_id=p_club_id and l.canonical_player_id=p.id and l.verified=true),'[]'::jsonb)
    ) order by cp.roster_status,p.name),'[]'::jsonb) j
    from public.club_players cp join public.players p on p.id=cp.player_id
    where cp.club_id=p_club_id and (p_season is null or cp.season=p_season)
  ), canonical_ids as (
    select cp.player_id from public.club_players cp where cp.club_id=p_club_id and (p_season is null or cp.season=p_season)
  ), all_ids as (
    select player_id id from canonical_ids
    union
    select l.source_player_id from public.player_identity_links l where l.club_id=p_club_id and l.canonical_player_id in (select player_id from canonical_ids) and l.verified=true
  ), samples_json as (
    select coalesce(jsonb_agg(to_jsonb(s) order by s.created_at desc),'[]'::jsonb) j
    from public.player_samples s where s.player_id in (select id from all_ids) and (p_season is null or s.season=p_season)
  ), game_json as (
    select coalesce(jsonb_agg(jsonb_build_object(
      'player_id',g.player_id,'player_name',g.player_name,'game_id',g.game_id,'season',g.season,'competition',g.competition,
      'team_name',g.team_name,'opponent_name',g.opponent_name,'starter',g.starter,'minutes',g.minutes,'stats',g.stats,'calculated',g.calculated,'created_at',g.created_at
    ) order by g.created_at desc),'[]'::jsonb) j
    from public.game_player_stats g where g.player_id in (select id from all_ids) and g.verified=true and (p_season is null or g.season=p_season)
  ), needs_json as (
    select coalesce(jsonb_agg(to_jsonb(n) order by case n.priority when 'high' then 1 when 'medium' then 2 else 3 end,n.created_at),'[]'::jsonb) j
    from public.club_roster_needs n where n.club_id=p_club_id and n.active=true and (p_season is null or n.season=p_season)
  ), shortlist_json as (
    select coalesce(jsonb_agg(jsonb_build_object('id',r.id,'player_id',r.player_id,'season',r.season,'role_key',r.role_key,'status',r.status,'notes',r.notes,'player',jsonb_build_object('name',p.name,'position',p.position)) order by r.updated_at desc),'[]'::jsonb) j
    from public.recruitment_shortlist r join public.players p on p.id=r.player_id
    where r.club_id=p_club_id and (p_season is null or r.season=p_season)
  )
  select jsonb_build_object('club_players',club_players_json.j,'samples',samples_json.j,'game_stats',game_json.j,'needs',needs_json.j,'shortlist',shortlist_json.j)
  into result from club_players_json,samples_json,game_json,needs_json,shortlist_json;
  return result;
end;$$;

