-- CourtIQ v187 · Player 360 + GM / Recruitment foundation.
-- Adds canonical player identity links, basketball-ops needs/shortlists and read RPCs.

create table if not exists public.player_identity_links (
  id bigint generated by default as identity primary key,
  club_id bigint not null references public.clubs(id) on delete cascade,
  canonical_player_id bigint not null references public.players(id) on delete cascade,
  source_player_id bigint not null references public.players(id) on delete cascade,
  source_label text not null default 'official game import',
  confidence numeric not null default 1 check (confidence >= 0 and confidence <= 1),
  evidence jsonb not null default '{}'::jsonb,
  verified boolean not null default false,
  created_at timestamptz not null default now(),
  unique (club_id, canonical_player_id, source_player_id)
);

create index if not exists player_identity_links_canonical_idx on public.player_identity_links(club_id,canonical_player_id);
create index if not exists player_identity_links_source_idx on public.player_identity_links(source_player_id);
alter table public.player_identity_links enable row level security;
drop policy if exists "members_read_identity_links" on public.player_identity_links;
create policy "members_read_identity_links" on public.player_identity_links
for select to authenticated using (private.is_club_member(club_id));

create table if not exists public.club_roster_needs (
  id bigint generated by default as identity primary key,
  club_id bigint not null references public.clubs(id) on delete cascade,
  season text not null,
  role_key text not null,
  label text not null,
  priority text not null default 'medium' check (priority in ('low','medium','high')),
  target_profile jsonb not null default '{}'::jsonb,
  notes text,
  active boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (club_id,season,role_key)
);

create table if not exists public.recruitment_shortlist (
  id bigint generated by default as identity primary key,
  club_id bigint not null references public.clubs(id) on delete cascade,
  season text not null,
  player_id bigint not null references public.players(id) on delete cascade,
  role_key text,
  status text not null default 'watch' check (status in ('watch','shortlist','review','contacted','closed')),
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (club_id,season,player_id)
);

alter table public.club_roster_needs enable row level security;
alter table public.recruitment_shortlist enable row level security;

drop policy if exists "members_read_roster_needs" on public.club_roster_needs;
create policy "members_read_roster_needs" on public.club_roster_needs
for select to authenticated using (private.is_club_member(club_id));

drop policy if exists "ops_manage_roster_needs" on public.club_roster_needs;
create policy "ops_manage_roster_needs" on public.club_roster_needs
for all to authenticated
using (exists (select 1 from public.club_members m where m.club_id=club_roster_needs.club_id and m.user_id=auth.uid() and m.role in ('owner','admin','gm','analyst','scout')))
with check (exists (select 1 from public.club_members m where m.club_id=club_roster_needs.club_id and m.user_id=auth.uid() and m.role in ('owner','admin','gm','analyst','scout')));

drop policy if exists "members_read_recruitment_shortlist" on public.recruitment_shortlist;
create policy "members_read_recruitment_shortlist" on public.recruitment_shortlist
for select to authenticated using (private.is_club_member(club_id));

drop policy if exists "ops_manage_recruitment_shortlist" on public.recruitment_shortlist;
create policy "ops_manage_recruitment_shortlist" on public.recruitment_shortlist
for all to authenticated
using (exists (select 1 from public.club_members m where m.club_id=recruitment_shortlist.club_id and m.user_id=auth.uid() and m.role in ('owner','admin','gm','analyst','scout')))
with check (exists (select 1 from public.club_members m where m.club_id=recruitment_shortlist.club_id and m.user_id=auth.uid() and m.role in ('owner','admin','gm','analyst','scout')));

