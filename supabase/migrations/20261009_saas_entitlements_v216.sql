-- CourtIQ SaaS Entitlements v216
-- Provider-neutral commercial layer: plan -> subscription -> usage -> hard limits.

create table if not exists public.saas_plans (
  plan_code text primary key,
  name text not null,
  monthly_game_limit integer,
  seat_limit integer,
  features jsonb not null default '{}'::jsonb,
  sort_order integer not null default 100,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint saas_plans_game_limit_check check (monthly_game_limit is null or monthly_game_limit >= 0),
  constraint saas_plans_seat_limit_check check (seat_limit is null or seat_limit >= 1)
);

