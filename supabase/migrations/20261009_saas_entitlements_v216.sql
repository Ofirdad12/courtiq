create table if not exists public.club_subscriptions (
  id bigint generated by default as identity primary key,
  club_id bigint not null unique references public.clubs(id) on delete cascade,
  plan_code text not null references public.saas_plans(plan_code),
  status text not null default 'trialing',
  payment_provider text,
  provider_customer_id text,
  provider_subscription_id text,
  current_period_start timestamptz not null default now(),
  current_period_end timestamptz not null default (now() + interval '14 days'),
  trial_ends_at timestamptz,
  cancel_at_period_end boolean not null default false,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint club_subscriptions_status_check check (status in ('trialing','active','past_due','paused','canceled','incomplete'))
);

create unique index if not exists club_subscriptions_provider_subscription_uidx
  on public.club_subscriptions(payment_provider, provider_subscription_id)
  where payment_provider is not null and provider_subscription_id is not null;

alter table public.club_subscriptions enable row level security;
drop policy if exists "members read club subscription" on public.club_subscriptions;
create policy "members read club subscription"
on public.club_subscriptions for select to authenticated
using (private.is_club_member(club_id));

revoke insert, update, delete on public.club_subscriptions from anon, authenticated;

