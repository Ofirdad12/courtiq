create or replace function private.courtiq_create_default_subscription()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.club_subscriptions(
    club_id,plan_code,status,current_period_start,current_period_end,trial_ends_at,metadata
  ) values (
    new.id,
    case when new.pilot then 'pilot' else 'trial' end,
    case when new.pilot then 'active' else 'trialing' end,
    now(),
    case when new.pilot then now() + interval '10 years' else now() + interval '14 days' end,
    case when new.pilot then null else now() + interval '14 days' end,
    jsonb_build_object('source','club_create_trigger')
  )
  on conflict (club_id) do nothing;
  return new;
end;
$$;

revoke all on function private.courtiq_create_default_subscription() from public, anon, authenticated;

drop trigger if exists courtiq_create_default_subscription on public.clubs;
create trigger courtiq_create_default_subscription
after insert on public.clubs
for each row execute function private.courtiq_create_default_subscription();

