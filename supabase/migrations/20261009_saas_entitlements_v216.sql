create or replace view public.club_entitlement_status
with (security_invoker = true)
as
select
  s.club_id,
  s.plan_code,
  p.name as plan_name,
  s.status,
  s.payment_provider,
  s.current_period_start,
  s.current_period_end,
  s.trial_ends_at,
  s.cancel_at_period_end,
  p.monthly_game_limit,
  p.seat_limit,
  p.features,
  coalesce(u.games_used,0)::integer as games_used,
  case
    when p.monthly_game_limit is null then null
    else greatest(p.monthly_game_limit - coalesce(u.games_used,0)::integer,0)
  end as games_remaining,
  case
    when s.status not in ('active','trialing') then false
    when s.current_period_end <= now() then false
    when p.monthly_game_limit is null then true
    else coalesce(u.games_used,0) < p.monthly_game_limit
  end as can_import_game
from public.club_subscriptions s
join public.saas_plans p on p.plan_code = s.plan_code
left join lateral (
  select count(*) as games_used
  from public.games g
  where g.club_id = s.club_id
    and g.created_at >= s.current_period_start
    and g.created_at < s.current_period_end
) u on true;

comment on view public.club_entitlement_status is
  'Tenant-safe commercial entitlement and current-period usage snapshot.';

revoke all on public.club_entitlement_status from public, anon;
grant select on public.club_entitlement_status to authenticated;

create or replace function private.courtiq_enforce_game_entitlement()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_status text;
  v_limit integer;
  v_start timestamptz;
  v_end timestamptz;
  v_used integer;
begin
  if new.club_id is null then
    raise exception using errcode='P0001', message='COURTIQ_CLUB_REQUIRED';
  end if;

  -- Re-importing the same official game is an update, not additional usage.
  if exists (
    select 1 from public.games g
    where g.club_id = new.club_id
      and g.provider = new.provider
      and g.external_id = new.external_id
  ) then
    return new;
  end if;

  select s.status,p.monthly_game_limit,s.current_period_start,s.current_period_end
    into v_status,v_limit,v_start,v_end
  from public.club_subscriptions s
  join public.saas_plans p on p.plan_code=s.plan_code
  where s.club_id=new.club_id;

  if not found then
    raise exception using errcode='P0001', message='COURTIQ_SUBSCRIPTION_REQUIRED';
  end if;

  if v_status not in ('active','trialing') then
    raise exception using errcode='P0001', message='COURTIQ_SUBSCRIPTION_INACTIVE';
  end if;

  if v_end <= now() then
    raise exception using errcode='P0001', message='COURTIQ_BILLING_PERIOD_ENDED';
  end if;

  if v_limit is null then
    return new;
  end if;

  select count(*)::integer into v_used
  from public.games g
  where g.club_id=new.club_id
    and g.created_at >= v_start
    and g.created_at < v_end;

  if v_used >= v_limit then
    raise exception using errcode='P0001', message='COURTIQ_GAME_LIMIT_REACHED';
  end if;

  return new;
end;
$$;

revoke all on function private.courtiq_enforce_game_entitlement() from public, anon, authenticated;

drop trigger if exists courtiq_enforce_game_entitlement on public.games;
create trigger courtiq_enforce_game_entitlement
before insert on public.games
for each row execute function private.courtiq_enforce_game_entitlement();

create or replace function private.courtiq_enforce_seat_entitlement()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_limit integer;
  v_used integer;
begin
  if exists (
    select 1 from public.club_members cm
    where cm.club_id=new.club_id and cm.user_id=new.user_id
  ) then
    return new;
  end if;

  select p.seat_limit into v_limit
  from public.club_subscriptions s
  join public.saas_plans p on p.plan_code=s.plan_code
  where s.club_id=new.club_id and s.status in ('active','trialing');

  if v_limit is null then
    return new;
  end if;

  select count(*)::integer into v_used
  from public.club_members cm
  where cm.club_id=new.club_id;

  if v_used >= v_limit then
    raise exception using errcode='P0001', message='COURTIQ_SEAT_LIMIT_REACHED';
  end if;

  return new;
end;
$$;

revoke all on function private.courtiq_enforce_seat_entitlement() from public, anon, authenticated;

drop trigger if exists courtiq_enforce_seat_entitlement on public.club_members;
create trigger courtiq_enforce_seat_entitlement
before insert on public.club_members
for each row execute function private.courtiq_enforce_seat_entitlement();

